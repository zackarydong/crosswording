"""Output: ASCII, plain text, .ipuz and PNG previews."""

from __future__ import annotations

import json
from pathlib import Path

from .grid import Grid, numbering, slots as get_slots
from .scoring import Scored
from .seeds import seed_crossings


def ascii_grid(grid: Grid, letters: list[str | None] | None = None, coords: bool = True) -> str:
    """'#' = block, '.' = white (or the seed letter if letters given). With
    coords, rows/cols are numbered 1-15 for easy hand transfer."""
    n = grid.n
    lines = []
    if coords:
        lines.append("    " + "".join(f"{c + 1:>3}" for c in range(n)))
    for r in range(n):
        cells = []
        for c in range(n):
            i = r * n + c
            if grid.b[i]:
                ch = "#"
            elif letters and letters[i]:
                ch = letters[i]
            else:
                ch = "."
            cells.append(ch)
        if coords:
            lines.append(f"{r + 1:>3} " + "".join(f"{ch:>3}" for ch in cells))
        else:
            lines.append("".join(cells))
    return "\n".join(lines)


def blocks_by_row(grid: Grid) -> str:
    n = grid.n
    out = []
    for r in range(n):
        cols = [str(c + 1) for c in range(n) if grid.b[r * n + c]]
        out.append(f"row {r + 1:>2}: " + (", ".join(cols) if cols else "-"))
    return "\n".join(out)


def seed_lines(s: Scored) -> list[str]:
    nums = numbering(s.cand.grid)
    out = []
    for word, slot in s.cand.seed_slots.items():
        num = nums.get(slot.cells[0], "?")
        d = "Across" if slot.direction == "A" else "Down"
        out.append(f"{word}: {num}-{d}, row {slot.row + 1}, col {slot.col + 1} ({slot.length})")
    out += seed_crossings(s.cand.seed_slots, s.cand.grid.n)
    return out


def stats_lines(s: Scored) -> list[str]:
    st = s.stats
    fr = s.fill
    lines = [
        f"score {s.score:.1f}",
        f"blocks {st.blocks} | words {st.words} | avg word length {st.avg_len:.2f} | "
        f"3-letter {st.threes} | flow {s.flow:.1f} | fillability {fr.score:.0f}",
        "lengths: " + ", ".join(f"{k}:{v}" for k, v in st.length_hist.items()),
        f"long non-seed entries (10+): {s.long_nonseed} | long stacked pairs: {s.stack_pairs}",
    ]
    if fr.dead:
        lines.append(
            "dead slots (0 candidates): " + "; ".join(f"{x.slot.label()} {x.pattern}" for x in fr.dead[:6])
        )
    if fr.tight:
        lines.append(
            "tight slots: " + "; ".join(f"{x.slot.label()} {x.pattern} ({x.candidates})" for x in fr.tight[:6])
        )
    return lines


def report(s: Scored, rank: int) -> str:
    g = s.cand.grid
    parts = [f"=== #{rank} ===", *stats_lines(s), "seeds:", *("  " + x for x in seed_lines(s))]
    if s.fillcheck is not None:
        parts.insert(2, "fill check: " + s.fillcheck.summary())
    parts += ["", ascii_grid(g), "", "with seeds:", ascii_grid(g, s.cand.letters)]
    if s.fillcheck is not None and s.fillcheck.letters:
        parts += ["", "sample fill (machine-made, only proves the grid can be filled):", ascii_grid(g, s.fillcheck.letters)]
    return "\n".join(parts)


def write_txt(s: Scored, rank: int, path: Path) -> None:
    g = s.cand.grid
    text = "\n".join(
        [
            report(s, rank),
            "",
            "plain grid:",
            g.to_text(),
            "",
            "block columns by row (for placing blocks by hand):",
            blocks_by_row(g),
            "",
        ]
    )
    path.write_text(text)


def to_ipuz(s: Scored, title: str) -> dict:
    g = s.cand.grid
    n = g.n
    nums = numbering(g)
    puzzle, solution = [], []
    for r in range(n):
        prow, srow = [], []
        for c in range(n):
            i = r * n + c
            if g.b[i]:
                prow.append("#")
                srow.append("#")
            else:
                prow.append(nums.get(i, 0))
                srow.append(s.cand.letters[i] if s.cand.letters[i] else None)
        puzzle.append(prow)
        solution.append(srow)
    clues = {"Across": [], "Down": []}
    seed_by_cells = {sl.cells: w for w, sl in s.cand.seed_slots.items()}
    for sl in get_slots(g, 3):
        key = "Across" if sl.direction == "A" else "Down"
        clues[key].append([nums[sl.cells[0]], f"[seed: {seed_by_cells[sl.cells]}]" if sl.cells in seed_by_cells else ""])
    for k in clues:
        clues[k].sort(key=lambda x: x[0])
    return {
        "version": "http://ipuz.org/v2",
        "kind": ["http://ipuz.org/crossword#1"],
        "title": title,
        "author": "",
        "notes": "Generated by gridfinder. Seed letters are filled in; other squares are empty.",
        "dimensions": {"width": n, "height": n},
        "block": "#",
        "empty": 0,
        "puzzle": puzzle,
        "solution": solution,
        "clues": clues,
    }


def write_png(s: Scored, path: Path, cell: int = 40) -> None:
    from PIL import Image, ImageDraw, ImageFont

    g = s.cand.grid
    n = g.n
    margin = 30
    size = margin + n * cell + 10
    img = Image.new("RGB", (size, size), "white")
    d = ImageDraw.Draw(img)

    def font(sz):
        for name in ("DejaVuSans.ttf", "Arial.ttf", "Helvetica.ttc"):
            try:
                return ImageFont.truetype(name, sz)
            except OSError:
                continue
        return ImageFont.load_default()

    f_num, f_letter, f_coord = font(10), font(20), font(13)
    nums = numbering(g)
    seed_cells = {i for sl in s.cand.seed_slots.values() for i in sl.cells}
    for k in range(n):
        x = margin + k * cell + cell // 2
        d.text((x, margin // 2), str(k + 1), fill="#555", font=f_coord, anchor="mm")
        d.text((margin // 2, x), str(k + 1), fill="#555", font=f_coord, anchor="mm")
    for r in range(n):
        for c in range(n):
            i = r * n + c
            x0, y0 = margin + c * cell, margin + r * cell
            box = [x0, y0, x0 + cell, y0 + cell]
            if g.b[i]:
                d.rectangle(box, fill="#111", outline="#111")
                continue
            d.rectangle(box, fill="#dcecff" if i in seed_cells else "white", outline="#888")
            if i in nums:
                d.text((x0 + 3, y0 + 2), str(nums[i]), fill="#333", font=f_num)
            if s.cand.letters[i]:
                d.text((x0 + cell / 2, y0 + cell / 2 + 4), s.cand.letters[i], fill="#1a4e8a", font=f_letter, anchor="mm")
    # Heavier lines every 5 squares make counting easier.
    for k in range(0, n + 1, 5):
        p = margin + k * cell
        d.line([p, margin, p, margin + n * cell], fill="#c33", width=1)
        d.line([margin, p, margin + n * cell, p], fill="#c33", width=1)
    d.rectangle([margin, margin, margin + n * cell, margin + n * cell], outline="#111", width=2)
    img.save(path)


def export_all(s: Scored, rank: int, outdir: Path) -> list[Path]:
    outdir.mkdir(parents=True, exist_ok=True)
    stem = outdir / f"grid-{rank:02d}"
    txt, ipuz, png = stem.with_suffix(".txt"), stem.with_suffix(".ipuz"), stem.with_suffix(".png")
    write_txt(s, rank, txt)
    ipuz.write_text(json.dumps(to_ipuz(s, f"gridfinder #{rank}"), indent=1))
    write_png(s, png)
    return [txt, ipuz, png]
